from app.ai.tools.base import BaseTool, ToolPermission
from app.config import settings

DOCUMENTS_DIR = Path("static/documents")
DOCUMENTS_DIR.mkdir(parents=True, exist_ok=True)


# --- 1. PowerPoint Presentation Tool ---

class SlideContent(BaseModel):
    title: str = Field(..., description="Title of the slide")
    bullets: list[str] = Field(default_factory=list, description="Key bullet points or talking notes for this slide")
    notes: Optional[str] = Field(None, description="Optional speaker notes for this slide")


class GeneratePresentationArgs(BaseModel):
    title: str = Field(..., description="Main presentation title")
    subtitle: Optional[str] = Field(None, description="Subtitle or presenter name / topic overview")
    slides: list[SlideContent] = Field(..., description="List of slides with titles and bullet points")
    theme: str = Field(
        default="modern_dark",
        description="Presentation color theme: 'modern_dark', 'professional_blue', 'emerald', 'luxury'"
    )


class GeneratePresentationTool(BaseTool):
    name = "generate_presentation"
    description = (
        "Generate a complete, professionally styled PowerPoint presentation (.pptx) with custom title slides, "
        "widescreen 16:9 layout, branded themes, and bullet points. Returns the downloadable file link."
    )
    permission = ToolPermission.WRITE
    args_schema = GeneratePresentationArgs

    _themes = {
        "modern_dark": {
            "bg": RGBColor(15, 23, 42),       # Slate 900
            "card_bg": RGBColor(30, 41, 59),  # Slate 800
            "title": RGBColor(248, 250, 252), # White
            "accent": RGBColor(56, 189, 248),  # Sky 400
            "body": RGBColor(203, 213, 225),   # Slate 300
        },
        "professional_blue": {
            "bg": RGBColor(10, 37, 64),
            "card_bg": RGBColor(21, 52, 85),
            "title": RGBColor(255, 255, 255),
            "accent": RGBColor(0, 212, 255),
            "body": RGBColor(220, 235, 252),
        },
        "emerald": {
            "bg": RGBColor(6, 44, 34),
            "card_bg": RGBColor(12, 68, 54),
            "title": RGBColor(240, 253, 244),
            "accent": RGBColor(52, 211, 153),
            "body": RGBColor(209, 250, 229),
        },
        "luxury": {
            "bg": RGBColor(24, 24, 27),
            "card_bg": RGBColor(39, 39, 42),
            "title": RGBColor(250, 250, 250),
            "accent": RGBColor(234, 179, 8),
            "body": RGBColor(228, 228, 231),
        },
    }

    async def execute(
        self,
        title: str,
        slides: list[dict[str, Any] | SlideContent],
        subtitle: Optional[str] = None,
        theme: str = "modern_dark",
        **kwargs: Any
    ) -> dict[str, Any]:
        prs = pptx.Presentation()
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5) # 16:9 widescreen
        blank_layout = prs.slide_layouts[6]

        th = self._themes.get(theme.lower(), self._themes["modern_dark"])

        # 1. Title Slide
        slide = prs.slides.add_slide(blank_layout)
        # Background
        bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(7.5))
        bg.fill.solid()
        bg.fill.fore_color.rgb = th["bg"]
        bg.line.fill.background()

        # Accent decorative bar
        bar = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(1.2), Inches(2.2), Inches(0.15), Inches(3.2))
        bar.fill.solid()
        bar.fill.fore_color.rgb = th["accent"]
        bar.line.fill.background()

        # Title text box
        txBox = slide.shapes.add_textbox(Inches(1.6), Inches(2.0), Inches(10.5), Inches(3.5))
        tf = txBox.text_frame
        tf.word_wrap = True

        p_title = tf.paragraphs[0]
        p_title.text = title
        p_title.font.size = Pt(44)
        p_title.font.bold = True
        p_title.font.color.rgb = th["title"]

        if subtitle:
            p_sub = tf.add_paragraph()
            p_sub.text = subtitle
            p_sub.font.size = Pt(22)
            p_sub.font.color.rgb = th["accent"]
            p_sub.space_before = Pt(14)

        p_footer = tf.add_paragraph()
        p_footer.text = "Generated by DAI • Advanced Intelligence"
        p_footer.font.size = Pt(13)
        p_footer.font.color.rgb = th["body"]
        p_footer.space_before = Pt(28)

        # 2. Content Slides
        for s_idx, s in enumerate(slides, start=1):
            s_title = s.get("title") if isinstance(s, dict) else s.title
            s_bullets = s.get("bullets", []) if isinstance(s, dict) else s.bullets

            c_slide = prs.slides.add_slide(blank_layout)
            c_bg = c_slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(7.5))
            c_bg.fill.solid()
            c_bg.fill.fore_color.rgb = th["bg"]
            c_bg.line.fill.background()

            # Top Header Bar
            h_box = c_slide.shapes.add_textbox(Inches(1.0), Inches(0.8), Inches(11.333), Inches(1.2))
            h_tf = h_box.text_frame
            h_tf.word_wrap = True
            hp = h_tf.paragraphs[0]
            hp.text = s_title
            hp.font.size = Pt(32)
            hp.font.bold = True
            hp.font.color.rgb = th["title"]

            # Content Card
            card = c_slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(1.0), Inches(2.2), Inches(11.333), Inches(4.5))
            card.fill.solid()
            card.fill.fore_color.rgb = th["card_bg"]
            card.line.fill.background()

            # Content text inside card
            c_box = c_slide.shapes.add_textbox(Inches(1.4), Inches(2.5), Inches(10.5), Inches(3.9))
            c_tf = c_box.text_frame
            c_tf.word_wrap = True

            first_bullet = True
            for b in s_bullets:
                if first_bullet:
                    bp = c_tf.paragraphs[0]
                    first_bullet = False
                else:
                    bp = c_tf.add_paragraph()
                    bp.space_before = Pt(12)

                bp.text = f"•   {b}"
                bp.font.size = Pt(18)
                bp.font.color.rgb = th["body"]

        # Save to static folder
        clean_slug = re.sub(r"[^a-zA-Z0-9_\-]", "_", title.strip().lower())[:35]
        file_id = uuid.uuid4().hex[:8]
        filename = f"{clean_slug}_{file_id}.pptx"
        file_path = DOCUMENTS_DIR / filename
        prs.save(str(file_path))

        file_url = f"{settings.BACKEND_URL}/static/documents/{filename}"

        return {
            "status": "success",
            "file_type": "pptx",
            "title": title,
            "filename": filename,
            "file_url": file_url,
            "slide_count": len(slides) + 1,
            "markdown": f"[📥 Download Presentation ({title}.pptx)]({file_url})",
            "message": f"Successfully created PowerPoint presentation with {len(slides) + 1} slides.",
        }


# --- 2. Word Document Tool ---

class SectionContent(BaseModel):
    heading: str = Field(..., description="Section heading")
    paragraphs: list[str] = Field(default_factory=list, description="Paragraphs of text for this section")
    bullets: list[str] = Field(default_factory=list, description="Optional bullet list items for this section")


class GenerateWordDocumentArgs(BaseModel):
    title: str = Field(..., description="Main title of the document")
    subtitle: Optional[str] = Field(None, description="Document subtitle or executive summary")
    sections: list[SectionContent] = Field(..., description="Document sections with headings, paragraphs, and bullets")


class GenerateWordDocumentTool(BaseTool):
    name = "generate_word_document"
    description = (
        "Generate a structured, professionally formatted Microsoft Word document (.docx) "
        "with custom styled title, sections, paragraphs, and bullet points. Returns the downloadable file link."
    )
    permission = ToolPermission.WRITE
    args_schema = GenerateWordDocumentArgs

    async def execute(
        self,
        title: str,
        sections: list[dict[str, Any] | SectionContent],
        subtitle: Optional[str] = None,
        **kwargs: Any
    ) -> dict[str, Any]:
        doc = docx.Document()

        # Page margins
        sections_page = doc.sections
        for sp in sections_page:
            sp.top_margin = DocxInches(1.0)
            sp.bottom_margin = DocxInches(1.0)
            sp.left_margin = DocxInches(1.0)
            sp.right_margin = DocxInches(1.0)

        # Main Title
        title_p = doc.add_paragraph()
        title_p.paragraph_format.space_before = DocxPt(0)
        title_p.paragraph_format.space_after = DocxPt(6)
        title_run = title_p.add_run(title)
        title_run.font.size = DocxPt(26)
        title_run.font.bold = True
        title_run.font.color.rgb = DocxRGBColor(15, 23, 42)

        # Subtitle
        if subtitle:
            sub_p = doc.add_paragraph()
            sub_p.paragraph_format.space_before = DocxPt(0)
            sub_p.paragraph_format.space_after = DocxPt(16)
            sub_run = sub_p.add_run(subtitle)
            sub_run.font.size = DocxPt(13)
            sub_run.font.italic = True
            sub_run.font.color.rgb = DocxRGBColor(71, 85, 105)

        # Separator line / divider
        div_p = doc.add_paragraph()
        div_p.paragraph_format.space_after = DocxPt(16)
        div_run = div_p.add_run("―" * 45)
        div_run.font.color.rgb = DocxRGBColor(203, 213, 225)

        # Sections
        for sec in sections:
            s_heading = sec.get("heading") if isinstance(sec, dict) else sec.heading
            s_paras = sec.get("paragraphs", []) if isinstance(sec, dict) else sec.paragraphs
            s_bullets = sec.get("bullets", []) if isinstance(sec, dict) else sec.bullets

            # Heading 1
            h_p = doc.add_paragraph()
            h_p.paragraph_format.space_before = DocxPt(16)
            h_p.paragraph_format.space_after = DocxPt(6)
            h_run = h_p.add_run(s_heading)
            h_run.font.size = DocxPt(16)
            h_run.font.bold = True
            h_run.font.color.rgb = DocxRGBColor(14, 116, 144) # Cyan 700

            # Paragraphs
            for text in s_paras:
                p = doc.add_paragraph()
                p.paragraph_format.space_before = DocxPt(0)
                p.paragraph_format.space_after = DocxPt(6)
                p.paragraph_format.line_spacing = 1.15
                r = p.add_run(text)
                r.font.size = DocxPt(11)
                r.font.color.rgb = DocxRGBColor(30, 41, 59)

            # Bullets
            for b in s_bullets:
                bp = doc.add_paragraph(style="List Bullet")
                bp.paragraph_format.space_before = DocxPt(2)
                bp.paragraph_format.space_after = DocxPt(2)
                br = bp.add_run(b)
                br.font.size = DocxPt(11)
                br.font.color.rgb = DocxRGBColor(30, 41, 59)

        # Save to static folder
        clean_slug = re.sub(r"[^a-zA-Z0-9_\-]", "_", title.strip().lower())[:35]
        file_id = uuid.uuid4().hex[:8]
        filename = f"{clean_slug}_{file_id}.docx"
        file_path = DOCUMENTS_DIR / filename
        doc.save(str(file_path))

        file_url = f"{settings.BACKEND_URL}/static/documents/{filename}"

        return {
            "status": "success",
            "file_type": "docx",
            "title": title,
            "filename": filename,
            "file_url": file_url,
            "section_count": len(sections),
            "markdown": f"[📥 Download Document ({title}.docx)]({file_url})",
            "message": f"Successfully created Word document with {len(sections)} sections.",
        }
